#!/usr/bin/env bash
# Серверная половина деплоя: миграции, переключение симлинка, рестарт.
# Файлы релиза уже лежат в $REL — их залил rsync со стороны runner-а.
#
# Архива больше нет: релиз весит 427 МБ (public 156 МБ, .next/server 127 МБ),
# и tar+scp гнал его целиком каждый раз. На узком канале это часы. rsync
# сверяет контрольные суммы с прошлым релизом и передаёт только то, что
# действительно изменилось; остальное сервер берёт из предыдущего каталога
# жёсткими ссылками.
set -euo pipefail

: "${REL:?путь релиза не передан (REL)}"

if [ ! -d "$REL" ]; then
  echo "каталог релиза $REL не найден — деплой остановлен" >&2
  exit 1
fi

# Схема базы приводится в порядок до переключения: новая версия не должна
# увидеть старую схему, а старая — новую.
if [ -f /etc/vibeui.env ]; then
  # Файл читается как shell-код, поэтому значение с пробелами или скобками
  # без кавычек роняет весь деплой. Проверяем до подстановки и говорим об
  # этом прямо: один раз строка SMTP_FROM уже стоила красной сборки.
  if ! bash -n /etc/vibeui.env; then
    echo "/etc/vibeui.env содержит синтаксическую ошибку — деплой остановлен" >&2
    exit 1
  fi

  set -a
  . /etc/vibeui.env
  set +a
  (cd "$REL" && bash scripts/migrate.sh)
fi

# Подмена симлинка атомарна: полусостояния не бывает.
ln -sfn "$REL" /srv/vibeui-live.tmp
mv -Tf /srv/vibeui-live.tmp /srv/vibeui-live

systemctl restart vibeui

# Держим три последних релиза: с жёсткими ссылками они делят между собой
# почти весь объём, а предыдущий нужен целым — следующий rsync берёт
# неизменные файлы именно из него.
ls -1dt /srv/vibeui-releases/* | tail -n +4 | xargs -r rm -rf

echo "released $REL"
