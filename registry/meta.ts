import type { RegistryItem } from "shadcn/schema"

import type { ItemGroup, ItemKind } from "@/registry/categories"

/**
 * Поле `meta` registry item'а. Доезжает в `/r/<name>.json`, то есть агент
 * видит его при установке.
 *
 * `kind` и `group` здесь необязательны и служат точечным исключением:
 * по умолчанию `kind` берётся из объявившего item реестра, а `group` — из
 * категории (см. `registry/categories.ts`). Проставлять их руками у каждого
 * item'а не нужно и не следует — это было бы дублирование metadata.
 */
/**
 * Настраиваемый атрибут item'а. Контролы — машиночитаемая форма `ai.adapt`:
 * объявлять контрол можно только для того, что инструкция и так разрешает
 * менять. Для того, что лежит в `ai.preserve`, контрола быть не может —
 * иначе интерфейс предлагает сломать то, что промпт запрещает трогать.
 *
 * Контрол настраивает **проп**, а не исходник: установленный файл обязан
 * оставаться побайтово равным тому, что раздаёт реестр (см. docs/CONTROLS.md).
 */
export type ItemControl = {
  /** Имя пропа компонента. `children` — тоже контрол. */
  prop: string
  label: string
} & (
  | { type: "text"; default: string; maxLength?: number }
  | { type: "select"; default: string; options: string[] }
  | { type: "color"; default: string }
  | { type: "boolean"; default: boolean }
  | { type: "number"; default: number; min?: number; max?: number }
)

export type ControlValue = string | number | boolean

/**
 * Слот контента блока — одна вместимость: «заголовок», «метрика», «фото
 * автора». Отвечает на вопрос человека с идеей, а не с готовым сайтом:
 * влезет ли сюда мой контент. Форма блока, не его текст (см. docs/SLOTS.md).
 */
export type CatalogSlot = {
  /** Роль как назовёт человек: «цитата», «автор», а не имя пропа. */
  role: string
  type: "text" | "stat" | "image" | "link" | "quote"
  /** Сколько таких слотов: число или диапазон «3–6». */
  count?: number | string
  required?: boolean
}

export type CatalogSlots = {
  /** Форма блока одной строкой: «отзывы сеткой: цитата + автор + фото». */
  shape: string
  /** Сколько текста держит блок: выбор по объёму контента. */
  density: "light" | "medium" | "heavy"
  /** Жёсткие требования к контенту: без них блок теряет смысл. */
  needs?: ("photo" | "video" | "logo" | "avatar" | "form")[]
  items: CatalogSlot[]
}

/** Переопределения контрола на другом языке. Тип контрола не меняется. */
export type LocalizedControl = {
  label?: string
  default?: ControlValue
}

/**
 * Что у item'а отличается на другом языке. Всё опционально: непереведённое
 * поле берётся из русского оригинала.
 */
export type LocalizedMeta = {
  title?: string
  description?: string
  /**
   * Техническая справка item'а. Живёт рядом с остальным переводом, а не в
   * `item.docs`, потому что `docs` — поле схемы shadcn и уезжает в реестр:
   * агент читает его на языке оригинала, человек на витрине — на своём.
   */
  docs?: string
  ai?: {
    summary?: string
    preserve?: string[]
    adapt?: string[]
    notes?: string[]
    usage?: string
  }
  controls?: Record<string, LocalizedControl>
  /**
   * Перевод слотов. `shape` — строкой, роли слотов — по индексу: число
   * элементов совпадает с оригиналом, иначе перевод не применяется.
   */
  slots?: {
    shape?: string
    items?: { role?: string }[]
  }
  /**
   * Демо-содержимое превью на другом языке. Устанавливаемый файл остаётся
   * как есть: русский текст внутри него — это дефолты компонента, а витрина
   * лишь передаёт другие пропсы. Меняется картинка на сайте, не исходник.
   */
  preview?: {
    props?: Record<string, unknown>
    states?: Record<string, unknown>[]
  }
}

export type CatalogMeta = {
  tags: string[]
  ai: {
    summary: string
    preserve: string[]
    adapt: string[]
    notes?: string[]
    /**
     * Имя экспорта компонента (`Hero001`). Путь установки выводится из
     * `files[0].target`, а символ — нет, поэтому его приходится объявлять.
     */
    export?: string
    /**
     * Канонический пример использования — JSX, который агент вставит
     * в разметку. Единственное поле, которое нельзя вывести: это
     * дизайнерское решение автора компонента.
     *
     * Для `kind: component` обязательно по соглашению — без него агент не
     * знает, с какими пропсами ставить мелкий компонент. Для `kind: block`
     * опционально: секция ставится целиком и агент прочитает установленный
     * файл.
     */
    usage?: string
  }
  /**
   * Что пользователь может настроить на витрине до выдачи агенту. Значения
   * едут в ссылке `/c/<name>?prop=value` и подставляются в сниппет
   * использования. Обязательны по соглашению для `kind: component`.
   */
  controls?: ItemControl[]
  /**
   * Какие из контролов вынесены значками в шапку карточки витрины. Имена
   * пропов из `controls`, порядок задаёт сам item.
   *
   * На карточке настройка крутится одной кнопкой, поэтому годятся только
   * `select`, `boolean`, `color` и `number` с обеими границами: у текста нет
   * состояния, которое можно перебрать. Полный набор контролов живёт на
   * странице item'а — сюда выносят два-три, без которых непонятен дизайн.
   */
  cardControls?: string[]
  /**
   * Закрытый item: превью видно всем, а исходник, команда установки и
   * инструкция для агента отдаются только по активной подписке. Пометка
   * живёт в metadata, потому что раздачу решает она же — сборка реестра
   * пропускает такие item'ы, и в `public/r/` их не бывает.
   */
  pro?: boolean
  /**
   * Переводы. Русский — базовый и лежит в обычных полях; здесь только то,
   * что отличается. Незаполненное поле откатывается к русскому: лучше
   * честно показать оригинал, чем машинный перевод.
   *
   * Подписи по умолчанию у компонента остаются русскими — они в исходнике,
   * который пользователь устанавливает, и менять его нельзя. Английская
   * витрина задаёт их через `controls.<prop>.default`: значение уезжает в
   * сниппет явным пропом, файл не трогается (см. docs/CONTROLS.md).
   */
  i18n?: Partial<Record<"en", LocalizedMeta>>
  /**
   * Как показывать item на витрине. Подложка сюда не входит: карточка всегда
   * открывается тёмной, светлую включает сам пользователь переключателем —
   * иначе витрина рябит, перекрашиваясь от item к item.
   */
  preview?: {
    /**
     * Ширина в кадре превью. `auto` — компонент занимает столько, сколько
     * просит (кнопка, плашка, аватар); `full` — ему нужна настоящая ширина
     * строки (поле формы, карточка, полоса прогресса), иначе он схлопнется
     * по содержимому и покажет не тот дизайн, который получит пользователь;
     * `section` — item занимает целый экран (фон, курсор), и в кадре ему
     * нужен тот же масштаб, что секции, иначе он рисуется точкой в углу;
     * `natural` — блок рисуется в натуральную величину по ширине карточки
     * без scale: container query сам сворачивает его в узкую раскладку,
     * текст остаётся читаемым, а не ужимается в нечитаемую мелочь.
     */
    width?: "auto" | "full" | "section" | "natural"
    /**
     * Пропсы только для витрины: миниатюра рендерит компонент без аргументов,
     * и состояние, которое иначе видно лишь по наведению или через
     * конфигуратор, на карточке не покажется. В устанавливаемый файл это
     * не попадает и дефолты компонента не меняет.
     */
    props?: Record<string, unknown>
    /**
     * Ряд состояний в миниатюре каталога: тот же компонент рендерится по
     * разу на каждый набор пропсов поверх `props`. Мелкому компоненту одного
     * экземпляра мало — кадр остаётся почти пустым, а состояния, ради
     * которых item и существует (размеры, присутствие, фото и его отсутствие),
     * с витрины не видны.
     *
     * Это по-прежнему только витрина: пользователь получает один компонент,
     * а сниппет в «Копировать для ИИ» собирается из контролов, не отсюда.
     * Как только человек трогает контрол на карточке, ряд уступает место
     * одному настроенному экземпляру.
     */
    states?: Record<string, unknown>[]
    /**
     * Пропорция кадра миниатюры для блока (`16/9` по умолчанию). Шапка сайта
     * высотой в одну строку, растянутая до 1280px, занимает в кадре 16/9
     * десятую часть высоты — остальное пустота, и с витрины блок не читается.
     * Низкому блоку нужен низкий кадр. На компонентные items не влияет:
     * у них кадр не масштабируется.
     */
    aspect?: string
  }
  /**
   * Вместимость блока: форма и слоты контента. Вход со стороны идеи —
   * человек выбирает блок по тому, влезет ли его контент, а не по чужой
   * истории в дефолтах (см. docs/SLOTS.md). На установку и сборку сценария
   * не влияет: это только витрина.
   */
  slots?: CatalogSlots
  kind?: ItemKind
  group?: ItemGroup
  internal?: boolean
  featured?: boolean
}

export type CatalogItem = RegistryItem & { meta?: CatalogMeta }
